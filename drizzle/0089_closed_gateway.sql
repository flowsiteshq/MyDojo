CREATE TABLE `gearOrders` (
	`id` int AUTO_INCREMENT NOT NULL,
	`orderReference` varchar(80) NOT NULL,
	`paypalOrderId` varchar(64),
	`paypalCaptureId` varchar(64),
	`paymentReference` varchar(128),
	`paymentProvider` varchar(32),
	`customerName` varchar(255) NOT NULL,
	`studentName` varchar(255) NOT NULL,
	`customerEmail` varchar(320) NOT NULL,
	`customerPhone` varchar(40),
	`productId` varchar(120) NOT NULL,
	`productName` varchar(255) NOT NULL,
	`size` varchar(32) NOT NULL,
	`color` varchar(32) NOT NULL,
	`amountCents` int NOT NULL,
	`currency` varchar(3) NOT NULL DEFAULT 'USD',
	`paymentStatus` enum('pending','paid','failed','cancelled','refunded') NOT NULL DEFAULT 'pending',
	`fulfillmentStatus` enum('pending','ready','fulfilled') NOT NULL DEFAULT 'pending',
	`paidAt` timestamp,
	`refundedAt` timestamp,
	`refundReference` varchar(128),
	`lastError` text,
	`createdAt` timestamp NOT NULL DEFAULT (now()),
	`updatedAt` timestamp NOT NULL DEFAULT (now()) ON UPDATE CURRENT_TIMESTAMP,
	CONSTRAINT `gearOrders_id` PRIMARY KEY(`id`),
	CONSTRAINT `gearOrders_orderReference_unique` UNIQUE(`orderReference`),
	CONSTRAINT `gearOrders_paypalOrderId_unique` UNIQUE(`paypalOrderId`),
	CONSTRAINT `gearOrders_paypalCaptureId_unique` UNIQUE(`paypalCaptureId`)
);
